"""Run every analysis and write tables, charts and a summary to outputs/.

    python scripts/run_all.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from feedopt import charts  # noqa: E402
from feedopt.data import load_all, load_benchmarks, load_price_history, load_requirements  # noqa: E402
from feedopt.model import check_requirements, formulate  # noqa: E402
from feedopt.planning import availability_aware_formulation, shortfall_report  # noqa: E402
from feedopt.scenarios import (  # noqa: E402
    category_summary, historical_cost, marine_cap, price_sweep, requirement_sweep, supply_shock,
)

OUT = ROOT / "outputs"
OUT.mkdir(exist_ok=True)
PRODUCTION_T = 20_000  # illustrative monthly production for one plant


def fmt_recipe(r) -> str:
    rec = r.recipe[r.recipe > 0.005]
    return "\n".join(f"| {i.replace('_', ' ')} | {v:.2f} |" for i, v in rec.items())


def main():
    nm, prices, req, limits = load_all("grower_1_2kg")
    lines = ["# Results summary", "", "Generated by `scripts/run_all.py`. All recipes are % as fed; nutrients are % of dry matter.", ""]

    # 1. Base case
    base = formulate(nm, prices, req, limits)
    assert base.feasible, base.status
    base.recipe.to_csv(OUT / "base_recipe.csv", header=["pct_as_fed"])
    base.nutrients_dm.to_csv(OUT / "base_nutrients_dm.csv", header=["value"])
    check = check_requirements(base.nutrients_dm, req)
    check.to_csv(OUT / "base_requirement_check.csv", index=False)
    base.shadow_prices.to_csv(OUT / "base_shadow_prices.csv", index=False)
    base.reduced_costs.to_csv(OUT / "base_reduced_costs.csv", header=["usd_per_t_price_drop_needed"])
    charts.recipe_bar(base.recipe, OUT / "01_base_recipe.png", "Least-cost grower feed (1 to 2 kg salmon)",
                      f"Raw material cost {base.cost_usd_per_t:,.0f} USD per tonne, March 2026 prices")
    charts.shadow_bar(base.shadow_prices, OUT / "02_shadow_prices.png", "Which constraints cost money?",
                      "Shadow price: extra USD per tonne of feed if the limit tightens by one unit")
    marine = base.recipe[["fish_meal", "fish_oil"]].sum()
    lines += ["## 1. Base case: grower feed, 1 to 2 kg fish", "",
              f"Raw material cost: **{base.cost_usd_per_t:,.0f} USD/t**. Marine ingredients: **{marine:.1f}%**.", "",
              "| Ingredient | % as fed |", "|---|---|", fmt_recipe(base), "",
              f"All {int(check['met'].sum())} of {len(check)} requirements met.", "",
              "Binding constraints and their shadow prices (USD/t per unit):", "",
              base.shadow_prices[["constraint", "usd_per_t_per_unit"]].round(2).to_markdown(index=False), "",
              "Price drop needed before an unused ingredient enters the recipe (USD/t):", "",
              base.reduced_costs.round(0).to_frame("usd_per_t").to_markdown(), ""]

    # 2. Smolt profile
    req_s = load_requirements("smolt_100_250g")
    smolt = formulate(nm, prices, req_s, limits)
    smolt.recipe.to_csv(OUT / "smolt_recipe.csv", header=["pct_as_fed"])
    lines += ["## 2. Smolt feed, 100 to 250 g fish", "",
              f"Higher protein and DP/DE targets push cost to **{smolt.cost_usd_per_t:,.0f} USD/t** "
              f"(+{smolt.cost_usd_per_t - base.cost_usd_per_t:,.0f}).", "",
              "| Ingredient | % as fed |", "|---|---|", fmt_recipe(smolt), ""]

    # 3. Fish oil price sweep
    fo = price_sweep(nm, prices, req, limits, "fish_oil", np.arange(1500, 9001, 250))
    fo.to_csv(OUT / "fish_oil_price_sweep.csv", index=False)
    charts.stacked_sweep(fo, "price", OUT / "03_fish_oil_price_sweep.png", "How the recipe reacts to fish oil prices",
                         "Grower feed re-optimized at each fish oil price", "Fish oil price (USD/t)")
    switch = fo[fo["algal_oil"] > 0.01]
    switch_txt = (f"Algal oil enters the recipe once fish oil passes about **{switch['price'].iloc[0]:,.0f} USD/t**."
                  if not switch.empty else "Algal oil never enters in this price range.")
    lines += ["## 3. Fish oil price sweep", "",
              f"Cost goes from {fo['cost_usd_per_t'].iloc[0]:,.0f} to {fo['cost_usd_per_t'].iloc[-1]:,.0f} USD/t "
              f"as fish oil goes from 1,500 to 9,000 USD/t. {switch_txt}", ""]

    # 4. EPA+DHA requirement sweep
    ed = requirement_sweep(nm, prices, req, limits, "epa_dha", "min", np.round(np.arange(0.6, 2.61, 0.1), 2))
    ed.to_csv(OUT / "epa_dha_sweep.csv", index=False)
    feasible = ed[ed["status"] == "Optimal"]
    charts.stacked_sweep(feasible, "requirement", OUT / "04_epa_dha_sweep.png", "The cost of omega-3 in the fillet",
                         "Recipe at each minimum EPA+DHA level", "Minimum EPA+DHA (% of dry matter)")
    charts.line_chart(feasible["requirement"], feasible["cost_usd_per_t"], OUT / "05_epa_dha_cost.png",
                      "Raw material cost vs EPA+DHA target", "Each point is a re-optimized recipe",
                      "Minimum EPA+DHA (% of dry matter)", "USD per tonne")
    r1 = feasible.loc[feasible["requirement"].sub(1.0).abs().idxmin(), "cost_usd_per_t"]
    r2 = feasible.loc[feasible["requirement"].sub(2.0).abs().idxmin(), "cost_usd_per_t"]
    lines += ["## 4. EPA+DHA target", "",
              f"Raising EPA+DHA from 1% (FAO minimum) to 2% costs **{r2 - r1:,.0f} USD/t** more "
              f"({r1:,.0f} to {r2:,.0f}).", ""]

    # 5. Supply shock: fish oil delivery late
    b, s = supply_shock(nm, prices, req, limits, "fish_oil", cap_pct=1.0, price_multiplier=1.3)
    shock = pd.concat({"base": b.recipe, "fish_oil_shock": s.recipe}, axis=1).fillna(0.0)
    shock.to_csv(OUT / "supply_shock_fish_oil.csv")
    lines += ["## 5. Supply shock: fish oil capped at 1% and 30% dearer", "",
              f"Status: {s.status}. Cost {b.cost_usd_per_t:,.0f} to {s.cost_usd_per_t:,.0f} USD/t "
              f"(+{s.cost_usd_per_t - b.cost_usd_per_t:,.0f}).", "",
              shock[(shock > 0.005).any(axis=1)].round(2).to_markdown(), ""]

    # 6. Sustainability: marine cap
    mc = marine_cap(nm, prices, req, limits, max_marine_pct=8)
    lines += ["## 6. Sustainability: fish meal + fish oil capped at 8%", "",
              f"Status: {mc.status}. Cost **{mc.cost_usd_per_t:,.0f} USD/t** "
              f"(+{mc.cost_usd_per_t - base.cost_usd_per_t:,.0f}).", "",
              "| Ingredient | % as fed |", "|---|---|", fmt_recipe(mc), ""]

    # 7. Historical cost with real World Bank prices
    hist = historical_cost(nm, prices, req, limits, load_price_history())
    hist.to_csv(OUT / "historical_cost.csv", index=False)
    q = hist[hist["period_type"] != "annual"]
    charts.line_chart(q["period"], q["cost_usd_per_t"], OUT / "06_historical_cost.png",
                      "Optimal recipe cost under real price history",
                      "World Bank prices for fish meal, soybean meal, maize and wheat", "Period", "USD per tonne",
                      rotate=True)
    lines += ["## 7. Recipe cost under 2023 to 2026 prices", "",
              hist[["period", "cost_usd_per_t", "fish_meal", "soy_protein_concentrate", "rapeseed_oil"]]
              .round(1).to_markdown(index=False), ""]

    # 8. Benchmarks
    bm = load_benchmarks()
    nor = bm[bm["benchmark"] == "norway_2020"].set_index("metric")["value"].copy()
    nor["marine"] = nor.pop("fish_meal") + nor.pop("fish_oil")
    cat = category_summary(base.recipe, nm)
    comp = pd.DataFrame({"This model": cat, "Norway 2020 (Nofima)": nor}).fillna(0.0)
    comp = comp.loc[["marine", "plant_protein", "vegetable_oil", "carbohydrate", "micro", "novel"]]
    comp.to_csv(OUT / "benchmark_categories.csv")
    charts.grouped_categories(comp, OUT / "07_benchmark_norway.png", "Model recipe vs real Norwegian salmon feed",
                              "Ingredient categories, % of feed. Norway 2020 from Aas et al. 2022 (Nofima)")
    prot = bm[bm["benchmark"] == "skretting_protec_4_5mm"].set_index("metric")["value"]
    dmf = base.nutrients_dm["dry_matter_pct_asfed"] / 100
    asfed = {k: base.nutrients_dm[k] * dmf for k in ["crude_protein", "crude_lipid", "ash", "phosphorus", "lys", "met", "thr", "arg"]}
    pcomp = pd.DataFrame({"model_grower_as_fed": pd.Series(asfed), "skretting_protec_as_fed": prot}).dropna().round(2)
    pcomp.to_csv(OUT / "benchmark_protec.csv")
    lines += ["## 8. Benchmarks", "",
              "Ingredient categories vs Norway's 2020 national average:", "", comp.round(1).to_markdown(), "",
              "Nutrients vs Skretting Protec 4.5 mm (a smaller-fish feed, so expect higher protein and lower fat):", "",
              pcomp.to_markdown(), ""]

    # 9. Planning: will we have the raw materials?
    st = pd.read_csv(ROOT / "data" / "raw" / "example_stock.csv").set_index("ingredient")
    sf = shortfall_report(base.recipe, PRODUCTION_T, st["stock_t"], st["inbound_t"])
    sf.to_csv(OUT / "planning_shortfall.csv")
    aware, caps = availability_aware_formulation(nm, prices, req, limits, PRODUCTION_T, st["stock_t"], st["inbound_t"])
    pd.concat({"planned": base.recipe, "availability_aware": aware.recipe}, axis=1).fillna(0.0).to_csv(
        OUT / "planning_reformulated.csv")
    lines += [f"## 9. Raw material planning for {PRODUCTION_T:,} t of feed (illustrative stock)", "",
              sf.to_markdown(), "",
              f"Re-formulating within available stock: status {aware.status}, cost "
              f"{aware.cost_usd_per_t:,.0f} USD/t (+{aware.cost_usd_per_t - base.cost_usd_per_t:,.0f}).", "",
              "| Ingredient | % as fed |", "|---|---|", fmt_recipe(aware), ""]

    (OUT / "summary.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
